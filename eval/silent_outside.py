"""List every silent change in an unedited function for manual classification.

Writes eval/silent_outside.tsv with one row per (instance, function). The
column ``label`` is filled in by hand with one of
    genuine    an effect of the patch on code it does not edit
    state      state shared across tests, such as caches or garbage collection
    revision   values that embed the revision or line numbers of edited files
    timing     thread or timing dependent values
    unclear    none of the above can be confirmed
Existing labels are kept when the file is regenerated.
"""
import csv
import json
import os
from pathlib import Path

HERE = Path(__file__).resolve().parent
# LaTeX macros with the numbers reported in the paper.
NUMBERS = Path(os.environ.get("BETELL_NUMBERS", HERE / "numbers"))


def main():
    target = HERE / "silent_outside.tsv"
    labels = {}
    if target.exists():
        with target.open() as handle:
            for row in csv.DictReader(handle, delimiter="\t"):
                labels[(row["instance"], row["function"])] = (row["label"], row["note"])
    rows = []
    for directory in sorted((HERE / "runs").iterdir()):
        report = directory / "report.json"
        if not report.exists():
            continue
        changes = json.loads(report.read_text())["changes"]
        functions = {}
        for change in changes:
            if change["kind"] != "outcome" and change["outside_diff"] and change["silent"]:
                functions.setdefault(change["location"], []).append(change)
        for function, items in functions.items():
            tests = sorted(set().union(*(set(c["tests"]) for c in items)))
            summary = "; ".join(
                f"{c['kind']} {c['detail']} new={c['after'][:1]} gone={c['before'][:1]}" for c in items)
            label, note = labels.get((directory.name, function), ("", ""))
            rows.append({"instance": directory.name, "function": function, "tests": len(tests),
                         "example_test": tests[0], "changes": summary[:400], "label": label, "note": note})
    with target.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]) if rows else ["instance"], delimiter="\t")
        writer.writeheader()
        writer.writerows(rows)
    print(f"{len(rows)} rows, {sum(1 for r in rows if not r['label'])} unlabeled")
    count = lambda label: sum(1 for r in rows if r["label"] == label)
    numbers = {
        "nSilentTotal": len(rows),
        "nSilentGenuine": count("genuine"),
        "nSilentGenuineInst": len({r["instance"] for r in rows if r["label"] == "genuine"}),
        "nSilentCache": count("state"),
        "nSilentOther": count("revision"),
        "nSilentTiming": count("timing"),
        "nSilentUnclear": count("unclear"),
    }
    print(numbers)
    target = NUMBERS / "numbers-manual.tex"
    target.parent.mkdir(parents=True, exist_ok=True)
    lines = ["% Generated by demo-code/eval/silent_outside.py from the manual labels in silent_outside.tsv"]
    lines += [f"\\newcommand{{\\{k}}}{{{v}\\xspace}}" for k, v in numbers.items()]
    target.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
